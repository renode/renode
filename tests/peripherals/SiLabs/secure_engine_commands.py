def push_user_data_write_command(data_hex: str, option: int = SE_USER_DATA_OPTION_SET) -> int:
    """
    Build a User Data Storage SET/FORCE_SET transaction: a single input descriptor of
    SE_USER_DATA_SIZE bytes carrying the token, plus the num_bytes parameter (see sl_se_write_user_data).
    Returns the input data ptr.
    """
    data = hex_to_byte_list(data_hex)
    assert len(data) == SE_USER_DATA_SIZE, "user data token must be SE_USER_DATA_SIZE bytes"
    reset_segment_index()
    input_descriptor, input_data_ptr = pack_dma_descriptor(is_last=True, data_size=SE_USER_DATA_SIZE, data=data)
    push_command(SE_COMMAND_ID_USER_DATA_STORAGE, option, (SE_USER_DATA_SIZE,), input_dma_descriptor_ptr=input_descriptor)
    return input_data_ptr

def push_user_data_remaining_command() -> int:
    """
    Build a User Data Storage "remaining writes" (option 0x03) transaction: a single 4-byte output
    descriptor and no parameters. Returns the output data ptr.
    """
    reset_segment_index()
    output_descriptor, output_data_ptr = pack_dma_descriptor(is_last=True, data_size=4)
    push_command(SE_COMMAND_ID_USER_DATA_STORAGE, SE_USER_DATA_OPTION_REMAINING, output_dma_descriptor_ptr=output_descriptor)
    return output_data_ptr

