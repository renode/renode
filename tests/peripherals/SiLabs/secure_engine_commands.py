def hash_interleaved_test():
    """
    Interleave two concurrent multipart streams (a SHA-256 vector and a SHA-1 vector) to prove
    the emulator does not retain hash-engine state between commands and instead picks up the
    firmware-supplied state on every HASHUPDATE / HASHFINISH.
    """

    stream_a_mode, stream_a_message, stream_a_expected = SHA_INTERLEAVED_TEST_VECTOR[0]
    stream_b_mode, stream_b_message, stream_b_expected = SHA_INTERLEAVED_TEST_VECTOR[1]

    stream_a_bytes = hex_to_byte_list(stream_a_message)
    stream_b_bytes = hex_to_byte_list(stream_b_message)
    block_a = SHA_BLOCK_SIZE[stream_a_mode]
    block_b = SHA_BLOCK_SIZE[stream_b_mode]

    state_a = hex_to_byte_list(SHA_INITIAL_STATE_HEX[stream_a_mode])
    state_b = hex_to_byte_list(SHA_INITIAL_STATE_HEX[stream_b_mode])

    cursor_a, cursor_b = 0, 0
    while (len(stream_a_bytes) - cursor_a >= block_a) or (len(stream_b_bytes) - cursor_b >= block_b):
        if len(stream_a_bytes) - cursor_a >= block_a:
            block = stream_a_bytes[cursor_a : cursor_a + block_a]
            state_ptr = push_hash_update_command(stream_a_mode, state_a, block)
            read_response(assert_success_status=True)
            state_a = _read_state(state_ptr, SHA_STATE_SIZE[stream_a_mode])
            cursor_a += block_a
        if len(stream_b_bytes) - cursor_b >= block_b:
            block = stream_b_bytes[cursor_b : cursor_b + block_b]
            state_ptr = push_hash_update_command(stream_b_mode, state_b, block)
            read_response(assert_success_status=True)
            state_b = _read_state(state_ptr, SHA_STATE_SIZE[stream_b_mode])
            cursor_b += block_b

    # Each push_hash_finish_command() resets segment_index, so stream A's output buffer is
    # reused by stream B. Snapshot each digest immediately after read_response, before pushing
    # the next finish, otherwise the second call overwrites the first one's scratch slot.
    digest_a_ptr = push_hash_finish_command(
        stream_a_mode, state_a, stream_a_bytes[cursor_a:], len(stream_a_bytes),
    )
    read_response(assert_success_status=True)
    digest_a = bytes(test_lib.read_byte(digest_a_ptr + i) for i in range(SHA_DIGEST_SIZE[stream_a_mode]))

    digest_b_ptr = push_hash_finish_command(
        stream_b_mode, state_b, stream_b_bytes[cursor_b:], len(stream_b_bytes),
    )
    read_response(assert_success_status=True)
    digest_b = bytes(test_lib.read_byte(digest_b_ptr + i) for i in range(SHA_DIGEST_SIZE[stream_b_mode]))

    expected_a = bytes(hex_to_byte_list(stream_a_expected))
    expected_b = bytes(hex_to_byte_list(stream_b_expected))
    test_lib.test_assert(
        digest_a == expected_a,
        f"Hash mismatch (interleaved SHA-1 stream): {digest_a.hex()} != {expected_a.hex()}",
    )
    test_lib.test_assert(
        digest_b == expected_b,
        f"Hash mismatch (interleaved SHA-256 stream): {digest_b.hex()} != {expected_b.hex()}",
    )
    print("  > Hash (interleaved multipart) Command OK")

def ecdsa_sign_command_test():
    """
    Exercise CommandId.SignatureSign (0x0600) against the CAVS SigGenComponent vectors
    (P-192 / P-256 / P-384 / P-521). The "Msg" field of these vectors is a precomputed
    digest, so the SE is invoked with hashed_message=true (sha_mode=None).

    ECDSA's random nonce means the produced signature changes on every call, so this test
    only checks the mailbox plumbing (status code, output descriptor length). Cryptographic
    correctness of the SE's ECDSA implementation is exercised by ecdsa_verify_command_test
    via the canonical (R || S) tuples generated from the same (d, digest).

    A second pass signs with sha_mode=SE_SHA_MODE_SHA256 over a synthetic raw message to
    exercise the on-device hashing code path during signing.
    """
    for idx, (key_size, digest, d, _qx, _qy, _r, _s) in enumerate(ECDSA_SIGN_VERIFY_VECTORS):
        label = f"SigGenComponent vector[{idx}] P-{key_size * 8}"

        signature_ptr = push_ecdsa_sign_command(key_size, d, digest, sha_mode=None)
        sign_status = read_response(assert_success_status=False)
        test_lib.test_assert(
            sign_status == SE_RESPONSE_OK,
            f"ECDSA sign {label}: unexpected status 0x{sign_status:08X}",
        )
        produced_signature = _bytes_to_hex(signature_ptr, 2 * key_size)
        test_lib.test_assert(
            len(produced_signature) == 4 * key_size,
            f"ECDSA sign {label}: unexpected signature length {len(produced_signature) // 2} bytes",
        )

    p256_priv = ECDSA_SIGN_VERIFY_VECTORS[3][2]
    raw_message = "00112233445566778899aabbccddeeff" * 4

    signature_ptr = push_ecdsa_sign_command(32, p256_priv, raw_message, sha_mode=SE_SHA_MODE_SHA256)
    sign_status = read_response(assert_success_status=False)
    test_lib.test_assert(
        sign_status == SE_RESPONSE_OK,
        f"ECDSA sign (P-256 + SHA-256): unexpected status 0x{sign_status:08X}",
    )
    produced_signature = _bytes_to_hex(signature_ptr, 64)
    test_lib.test_assert(
        len(produced_signature) == 128,
        f"ECDSA sign (P-256 + SHA-256): unexpected signature length {len(produced_signature) // 2} bytes",
    )

    print("  > ECDSA Sign Command OK")

def ecdsa_verify_command_test():
    """
    Exercise CommandId.SignatureVerify (0x0601):
      - CAVS SigGenComponent vectors: verify each canonical (R || S) against (Q, digest)
        with sha_mode=None (the SE treats the input as a precomputed digest).
      - FIPS-186-4 P-256 / SHA-256 vectors: verify each (R || S) against (Q, raw message)
        with sha_mode=SE_SHA_MODE_SHA256, asserting the expected pass/fail outcome.
    Combined, the two passes cover both the precomputed-digest and on-device-hashing code
    paths as well as the SE_RESPONSE_OK / SE_RESPONSE_INVALID_SIGNATURE response paths.
    """
    for idx, (key_size, digest, _d, qx, qy, r, s) in enumerate(ECDSA_SIGN_VERIFY_VECTORS):
        public_key = qx + qy
        canonical_signature = r + s
        label = f"SigGenComponent vector[{idx}] P-{key_size * 8}"

        push_ecdsa_verify_command(key_size, public_key, digest, canonical_signature, sha_mode=None)
        status = read_response(assert_success_status=False)
        test_lib.test_assert(
            status == SE_RESPONSE_OK,
            f"ECDSA verify (canonical) {label}: status 0x{status:08X} signature={canonical_signature}",
        )

    for idx, (qx, qy, msg, r, s, expected_ok) in enumerate(ECDSA_VERIFY_VECTORS_P256_SHA256):
        public_key = qx + qy
        signature = r + s
        label = f"FIPS-186-4 vector[{idx}] expect={'P' if expected_ok else 'F'}"

        push_ecdsa_verify_command(32, public_key, msg, signature, sha_mode=SE_SHA_MODE_SHA256)
        status = read_response(assert_success_status=False)
        expected = SE_RESPONSE_OK if expected_ok else SE_RESPONSE_INVALID_SIGNATURE
        test_lib.test_assert(
            status == expected,
            f"ECDSA verify {label}: status 0x{status:08X}, expected 0x{expected:08X}",
        )

    print("  > ECDSA Verify Command OK")

