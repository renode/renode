def reset_segment_index() -> None:
    global segment_index
    segment_index = 0

def get_segment(move_index: bool = True) -> int:
    global segment_index
    assert segment_index < MAX_SEGMENTS, "Out of segments"
    addr = SCRATCH_SRAM_BASE + segment_index * SEGMENT_SIZE
    if move_index:
        segment_index += 1
    return addr

def hex_to_byte_list(hex_digits: str) -> List[int]:
    assert isinstance(hex_digits, str), "hex_digits must be a str"
    s = hex_digits.strip().lower()
    assert len(s) % 2 == 0, "hex string length must be even"
    assert all(c in "0123456789abcdef" for c in s), "hex string must be hexadecimal"
    return [int(s[i : i + 2], 16) for i in range(0, len(s), 2)]

def assert_ciphertext_matches(ciphertext_data_ptr: int, expected_ciphertext: str) -> None:
    expected_ciphertext_bytes = hex_to_byte_list(expected_ciphertext)
    actual_ciphertext_bytes = []
    for i in range(len(expected_ciphertext_bytes)):
        actual_ciphertext_bytes.append(test_lib.read_byte(ciphertext_data_ptr + i))
    test_lib.test_assert(actual_ciphertext_bytes == expected_ciphertext_bytes, f"Ciphertext does not match expected: {actual_ciphertext_bytes} != {expected_ciphertext_bytes}")

