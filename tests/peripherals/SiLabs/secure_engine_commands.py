def import_key_command_test():
    """
    Exercise CommandId.ImportKey (0x0100) against the SDK contract in
    sl_se_import_key (sl_se_manager_key_handling.c):

      - key_in storage  : EXTERNAL_PLAINTEXT (only this is accepted)
      - key_out storage : one of INTERNAL_VOLATILE, EXTERNAL_WRAPPED, INTERNAL_KSU
      - any other destination returns SL_STATUS_INVALID_PARAMETER

    Coverage:
      * Negative: EXTERNAL_PLAINTEXT destination -> INVALID_PARAMETER
      * Positive: INTERNAL_VOLATILE destination  -> OK + round-trip via EXPORT_KEY
      * Positive: EXTERNAL_WRAPPED destination   -> OK + envelope inspected + round-trip
      * Positive: INTERNAL_KSU destination       -> OK (no host-visible payload)
    """

    plaintext_key_hex = "0123456789abcdef0123456789abcdef"  # 16 bytes
    plaintext_key_bytes = hex_to_byte_list(plaintext_key_hex)
    key_length = len(plaintext_key_bytes)

    # ---- Negative: Unprotected destination ----
    push_import_key_command(
        _raw_keyspec(0, SE_KEY_MODE_UNPROTECTED, SE_KEY_RESTRICTION_UNLOCKED),
        plaintext_key_hex,
    )
    status = read_response(assert_success_status=False)
    test_lib.test_assert(
        status == SE_RESPONSE_INVALID_PARAMETER,
        f"IMPORT_KEY Unprotected dest: status 0x{status:08X}, expected 0x{SE_RESPONSE_INVALID_PARAMETER:08X}",
    )

    # ---- Positive: Volatile destination ----
    volatile_index = 1
    push_import_key_command(
        _raw_keyspec(volatile_index, SE_KEY_MODE_VOLATILE, SE_KEY_RESTRICTION_UNLOCKED),
        plaintext_key_hex,
    )
    read_response(assert_success_status=True)

    out_ptr = push_export_key_command(
        _raw_keyspec(volatile_index, SE_KEY_MODE_VOLATILE, SE_KEY_RESTRICTION_UNLOCKED),
        key_length,
    )
    read_response(assert_success_status=True)
    exported = _bytes_to_hex(out_ptr, key_length)
    test_lib.test_assert(
        exported == plaintext_key_hex,
        f"IMPORT_KEY/EXPORT_KEY (volatile) roundtrip mismatch: {exported} != {plaintext_key_hex}",
    )

    # ---- Positive: Wrapped destination ----
    envelope_ptr = push_import_key_command(
        _raw_keyspec(0, SE_KEY_MODE_WRAPPED, SE_KEY_RESTRICTION_UNLOCKED),
        plaintext_key_hex,
    )
    read_response(assert_success_status=True)

    iv_bytes = [test_lib.read_byte(envelope_ptr + i) for i in range(SE_WRAPPED_KEY_IV_LENGTH)]
    key_bytes_out = [
        test_lib.read_byte(envelope_ptr + SE_WRAPPED_KEY_IV_LENGTH + i) for i in range(key_length)
    ]
    tag_bytes = [
        test_lib.read_byte(envelope_ptr + SE_WRAPPED_KEY_IV_LENGTH + key_length + i)
        for i in range(SE_WRAPPED_KEY_TAG_LENGTH)
    ]
    test_lib.test_assert(
        all(b == SE_WRAPPED_KEY_IV_MARKER for b in iv_bytes),
        f"IMPORT_KEY wrapped envelope IV markers invalid: {bytes(iv_bytes).hex()}",
    )
    test_lib.test_assert(
        key_bytes_out == plaintext_key_bytes,
        f"IMPORT_KEY wrapped envelope key mismatch: {bytes(key_bytes_out).hex()} != {plaintext_key_hex}",
    )
    test_lib.test_assert(
        all(b == SE_WRAPPED_KEY_TAG_MARKER for b in tag_bytes),
        f"IMPORT_KEY wrapped envelope tag markers invalid: {bytes(tag_bytes).hex()}",
    )

    # Snapshot the envelope before pushing the next command (which calls reset_segment_index()
    # and reuses the same scratch RAM).
    envelope_hex = bytes(iv_bytes + key_bytes_out + tag_bytes).hex()

    out_ptr = push_export_key_command(
        _raw_keyspec(0, SE_KEY_MODE_WRAPPED, SE_KEY_RESTRICTION_UNLOCKED),
        key_length,
        wrapped_envelope_hex=envelope_hex,
    )
    read_response(assert_success_status=True)
    exported = _bytes_to_hex(out_ptr, key_length)
    test_lib.test_assert(
        exported == plaintext_key_hex,
        f"IMPORT_KEY/EXPORT_KEY (wrapped) roundtrip mismatch: {exported} != {plaintext_key_hex}",
    )

    # ---- Positive: KSU destination (Series 3 only path; no host-visible payload) ----
    push_import_key_command(
        _raw_keyspec(7, SE_KEY_MODE_KSU, SE_KEY_RESTRICTION_UNLOCKED),
        plaintext_key_hex,
    )
    read_response(assert_success_status=True)

    print("  > Import Key Command OK")

