    nonce_bytes = hex_to_byte_list(nonce)

    reset_segment_index()
    input_root, _ = pack_dma_descriptor(is_last=False, data_size=len(auth_data_bytes), data=auth_data_bytes)
    pack_dma_descriptor(is_last=False, data_size=len(key_bytes), data=key_bytes)
    _, message_length_ptr = pack_dma_descriptor(is_last=False, data_size=4)
    test_lib.write_doubleword(message_length_ptr, total_message_length)
    pack_dma_descriptor(is_last=False, data_size=len(nonce_bytes), data=nonce_bytes)
    pack_dma_descriptor(is_last=True, data_size=len(aad_bytes), data=aad_bytes)

