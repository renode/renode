def pack_dma_descriptor(is_last: bool, data_size: int, data: Sequence[int] = None, transfer_options: int = 0) -> Tuple[int, int]:
    """
    Lay out one SE DMA descriptor in scratch RAM (see UnpackDmaDescriptor in SiLabs_SecureElement.cs).

    Word0: dataPointer
    Word1: nextDescriptorPtr (use SE_DMA_NULL_DESCRIPTOR to terminate)
    Word2: (transferOptions << 28) | (dataSize & 0x0FFFFFFF)

    Returns (descriptor_address, data_pointer). The next descriptor in a chain must be laid out
    starting at the address that follows the current data segment — do not advance segment_index
    twice for "next" or the following pack_dma_descriptor would skip a slot.
    """

    descriptor_address = get_segment()
    data_pointer = get_segment()
    if is_last:
        next_descriptor_pointer = SE_DMA_NULL_DESCRIPTOR
    else:
        next_descriptor_pointer = get_segment(False)
    word2 = (transfer_options << 28) | data_size
    test_lib.write_doubleword(descriptor_address, data_pointer)
    test_lib.write_doubleword(descriptor_address + 4, next_descriptor_pointer)
    test_lib.write_doubleword(descriptor_address + 8, word2)
    if data is not None:
        assert len(data) == data_size, "data length must match data_size"
        for i in range(data_size):
            test_lib.write_byte(data_pointer + i, data[i])
    return descriptor_address, data_pointer

def push_command(command_id: int, command_options: int, parameters: Sequence[int] = (), input_dma_descriptor_ptr: int = 0, output_dma_descriptor_ptr: int = 0) -> Tuple[int, Sequence[int]]:
    """
    Build (tx_header, fifo_payload_words) for the emulated SEMAILBOX / SecureElement mailbox protocol.

    Matches SiLabs_SecureElement.ProcessCommand(): after the TX header word, series3 expects
    command_handle, command_options (command id in upper 16 bits), input DMA root, output DMA root,
    then each command parameter word. The TX header value is the total message size in bytes
    (multiple of 4), consistent with TxHeaderSetCallback / TXHEADER in SiLabs_SEMAILBOX_2.cs.

    The input/output DMA descriptor root pointers are always present in the message; pass 0
    (NULL) when the command has no input or no output descriptor list. This mirrors
    sli_se_mailbox_execute_command(), which writes command->data_in / command->data_out to
    the FIFO unconditionally and uses NULL when there is no descriptor chain (e.g. the
    Random command has no input descriptor and a single output descriptor).

    Push the command to the SEMAILBOX.
    """
    command_options = (command_id << 16) | command_options
    payload = [SE_DEFAULT_COMMAND_HANDLE, command_options, input_dma_descriptor_ptr, output_dma_descriptor_ptr, *parameters]
    total_words = 1 + len(payload)
    tx_header = total_words * 4
    write_semailbox_register(SEMAILBOX_REG_TX_HEADER, tx_header)
    for word in payload:
        write_semailbox_register(SEMAILBOX_REG_FIFO0, word)

def read_response(assert_success_status: bool = True):
    """
    Read status word and command handle from the RX FIFO via SEMAILBOX RX_HEADER
    (see WriteResponse in SiLabs_SecureElement.cs).
    """
    status = read_semailbox_register(SEMAILBOX_REG_RX_HEADER)
    handle = read_semailbox_register(SEMAILBOX_REG_RX_HEADER)
    test_lib.test_assert(handle == SE_DEFAULT_COMMAND_HANDLE, f"Unexpected command handle: 0x{handle:08X}")
    if assert_success_status:
        test_lib.test_assert(status == SE_RESPONSE_OK, f"Unexpected status: 0x{status:08X}")
    return status

def create_key_metadata(key_index: int, key_type: int, key_mode: int, key_restriction: int, key_length: int = 0):
    """
    Create a key metadata word.

    For raw (symmetric) keys, key_length is encoded in bits [14:0] (see
    UnpackRawKeyMetadata in SiLabs_SecureElement.cs). Pass the byte length of the key
    material when building encrypt/decrypt/HMAC command parameters.
    """
    assert 0 <= key_index <= 0xFF, "key_index must fit in 8 bits"
    assert 0 <= key_length <= 0x7FFF, "key_length must fit in 15 bits"
    return (
        (key_type & 0xF) << 28
        | (key_mode & 0x3) << 26
        | (key_restriction & 0x3) << 24
        | (key_index & 0xFF) << 16
        | (key_length & 0x7FFF)
    )

def push_random_command(random_length: int):
    """
    Build a Random (CommandId.Random) mailbox transaction and push it to the SEMAILBOX.
    Returns the address of the data segment containing the random data.
    """
    reset_segment_index()
    output_descriptor, random_data_ptr = pack_dma_descriptor(is_last=True, data_size=random_length)
    push_command(SE_COMMAND_ID_RANDOM, 0, (random_length,), output_dma_descriptor_ptr=output_descriptor)
    return random_data_ptr

