def _run_multipart_ccm_encrypt(key: str, nonce: str, aad: Optional[str], plaintext: str, tag_size: int, chunk_size: int) -> Tuple[str, str]:
    """
    Drive START -> (ADD)* -> FINISH for one CCM multi-part encrypt, feeding `plaintext` in chunks
    of up to `chunk_size` bytes (rounded down to a multiple of 16) at a time; the trailing 0..15
    residual bytes are always held back for FINISH, matching sl_se_ccm_multipart_update()'s own
    buffering. Returns (ciphertext_hex, tag_hex).
    """
    plaintext_bytes = hex_to_byte_list(plaintext)
    total_length = len(plaintext_bytes)

    context_ptr = push_aes_ccm_multipart_start_command(
        encrypt=True, key=key, nonce=nonce, aad=aad, total_message_length=total_length, tag_size=tag_size,
    )
    read_response(assert_success_status=True)
    context = _bytes_to_hex(context_ptr, SE_CCM_CONTEXT_SIZE)

    ciphertext_bytes = bytearray()
    cursor = 0
    full_blocks_end = total_length - (total_length % 16)
    add_chunk_size = max(chunk_size - (chunk_size % 16), 16)
    while cursor < full_blocks_end:
        chunk_end = min(cursor + add_chunk_size, full_blocks_end)
        chunk = plaintext_bytes[cursor:chunk_end]
        output_data_ptr, output_context_ptr = push_aes_ccm_multipart_add_command(
            encrypt=True, key=key, context=context, input_data=bytes(chunk).hex(),
        )
        read_response(assert_success_status=True)
        ciphertext_bytes.extend(bytes(test_lib.read_byte(output_data_ptr + i) for i in range(len(chunk))))
        context = _bytes_to_hex(output_context_ptr, SE_CCM_CONTEXT_SIZE)
        cursor = chunk_end

    final_data = plaintext_bytes[cursor:]
    output_data_ptr, output_tag_ptr = push_aes_ccm_multipart_finish_command(
        encrypt=True, key=key, context=context, tag_size=tag_size, final_data=bytes(final_data).hex(),
    )
    read_response(assert_success_status=True)
    ciphertext_bytes.extend(bytes(test_lib.read_byte(output_data_ptr + i) for i in range(len(final_data))))
    tag_hex = _bytes_to_hex(output_tag_ptr, tag_size)

    return bytes(ciphertext_bytes).hex(), tag_hex

