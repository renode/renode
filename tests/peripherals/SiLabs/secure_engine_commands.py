    pack_dma_descriptor(is_last=False, data_size=len(input_bytes), data=input_bytes)
    pack_dma_descriptor(is_last=True, data_size=len(tag_bytes), data=tag_bytes)

    output_root, plaintext_data_ptr = pack_dma_descriptor(is_last=True, data_size=len(input_bytes))

    nonce_and_tag_sizes = ((len(nonce_bytes) & 0xFFFF) << 16) | (len(tag_bytes) & 0xFFFF)
